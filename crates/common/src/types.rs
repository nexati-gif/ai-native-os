//! Core type definitions for the orchestrator

use std::collections::BTreeMap;
use std::time::Duration;
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Unique identifier for a proposal
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct ProposalId(pub Uuid);

impl ProposalId {
    pub fn new() -> Self {
        Self(Uuid::new_v4())
    }
}

impl Default for ProposalId {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Display for ProposalId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Trigger for an active cycle
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum Trigger {
    /// Manual trigger from user (CLI, UI, API)
    Manual { reason: String },
    /// Scheduled trigger (cron-like)
    Scheduled { schedule_id: String },
    /// Anomaly detected by passive observation
    Anomaly { anomaly_id: String, severity: AnomalySeverity },
    /// Federation sync received new approved proposals
    FederationSync { peer_id: String },
    /// System boot / orchestrator start
    Boot,
    /// Periodic optimization window
    OptimizationWindow,
}

/// Severity of detected anomaly
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AnomalySeverity {
    Info,
    Warning,
    Critical,
}

/// Proposal generated by the planner
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Proposal {
    pub id: ProposalId,
    pub trigger: Trigger,
    pub timestamp: DateTime<Utc>,
    pub kind: ProposalKind,
    pub description: String,
    pub rationale: String,
    pub risk_level: RiskLevel,
    pub estimated_impact: ImpactEstimate,
    pub test_plan: TestPlan,
    pub rollback_plan: RollbackPlan,
    pub affected_components: Vec<Component>,
    pub diff: Option<String>, // Unified diff of changes
    pub metadata: BTreeMap<String, String>,
}

/// Kind of proposal
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ProposalKind {
    SysctlTuning,
    EbpfProgram,
    KernelModule,
    KernelPatch,
    NixConfig,
    ServiceConfig,
    ModelUpdate,
    PolicyUpdate,
    FederationSync,
    Custom(String),
}

/// Risk level of a proposal
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum RiskLevel {
    None,
    Low,
    Medium,
    High,
    Critical,
}

/// Estimated impact of a proposal
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImpactEstimate {
    pub performance_delta_pct: f64,    // Positive = improvement
    pub memory_delta_mib: i64,         // Positive = more memory
    pub cpu_delta_pct: f64,            // Positive = more CPU
    pub latency_delta_pct: f64,        // Positive = higher latency
    pub battery_delta_pct: f64,        // Positive = more drain
    pub stability_risk: RiskLevel,
    pub security_risk: RiskLevel,
    pub compatibility_risk: RiskLevel,
}

/// Test plan for validation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TestPlan {
    pub unit_tests: Vec<String>,
    pub integration_tests: Vec<String>,
    pub benchmarks: Vec<BenchmarkSpec>,
    pub canary_duration_secs: u64,
    pub success_criteria: SuccessCriteria,
}

/// Benchmark specification
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BenchmarkSpec {
    pub name: String,
    pub command: String,
    pub args: Vec<String>,
    pub baseline_metric: Option<f64>,
    pub target_improvement_pct: f64,
}

/// Success criteria for validation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SuccessCriteria {
    pub min_tests_passing: usize,
    pub max_regression_pct: f64,
    pub min_improvement_pct: f64,
    pub statistical_significance: f64, // p-value threshold
    pub require_all_benchmarks: bool,
}

/// Rollback plan
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RollbackPlan {
    pub automatic: bool,
    pub trigger_conditions: Vec<RollbackTrigger>,
    pub estimated_downtime_secs: u64,
    pub data_loss_risk: RiskLevel,
}

/// Rollback trigger condition
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum RollbackTrigger {
    TestFailure { test_name: String },
    MetricRegression { metric: String, threshold_pct: f64 },
    Crash { component: String },
    Timeout { operation: String },
    Manual,
}

/// System component affected by proposal
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Component {
    KernelScheduler,
    KernelMemory,
    KernelNetwork,
    KernelFilesystem,
    KernelSecurity,
    EbpfPrograms,
    KernelModules,
    NixPackages,
    SystemdServices,
    ModelWeights,
    LoRAAdapters,
    RAGIndex,
    PolicyEngine,
    Federation,
    UI,
    Custom(u32),
}

/// Human approval decision
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Approval {
    pub proposal_id: ProposalId,
    pub approved: bool,
    pub modified_proposal: Option<Proposal>,
    pub reason: Option<String>,
    pub timestamp: DateTime<Utc>,
    pub approver: String, // User identifier
}

/// Validation result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ValidationResult {
    pub proposal_id: ProposalId,
    pub passed: bool,
    pub metrics: ValidationMetrics,
    pub test_results: Vec<TestResult>,
    pub benchmark_results: Vec<BenchmarkResult>,
    pub failure: Option<ValidationFailure>,
    pub timestamp: DateTime<Utc>,
    pub duration: Duration,
}

/// Validation metrics comparison
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ValidationMetrics {
    pub before: BTreeMap<String, f64>,
    pub after: BTreeMap<String, f64>,
    pub deltas: BTreeMap<String, f64>,
    pub statistical_tests: BTreeMap<String, StatisticalTest>,
}

/// Individual test result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TestResult {
    pub name: String,
    pub passed: bool,
    pub duration: Duration,
    pub output: Option<String>,
    pub error: Option<String>,
}

/// Benchmark result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BenchmarkResult {
    pub name: String,
    pub baseline: f64,
    pub current: f64,
    pub delta_pct: f64,
    pub passed: bool,
    pub confidence_interval: (f64, f64),
    pub p_value: f64,
}

/// Validation failure details
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ValidationFailure {
    pub kind: FailureKind,
    pub message: String,
    pub component: Component,
    pub recoverable: bool,
}

/// Kind of validation failure
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum FailureKind {
    TestFailure,
    BenchmarkRegression,
    Crash,
    Timeout,
    PolicyViolation,
    ResourceExhaustion,
    DataCorruption,
    SecurityViolation,
}

/// Statistical test result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StatisticalTest {
    pub test_name: String,
    pub statistic: f64,
    pub p_value: f64,
    pub significant: bool,
    pub effect_size: f64,
}

/// Cycle execution result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum CycleResult {
    Promoted(ValidationMetrics),
    Rejected,
    RolledBack(ValidationFailure),
    Failed(Error),
    PendingApproval(ProposalId),
}

/// Device identifier for federation
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct DeviceId(pub String);

impl DeviceId {
    pub fn new(hostname: &str) -> Self {
        Self(hostname.to_string())
    }
}

